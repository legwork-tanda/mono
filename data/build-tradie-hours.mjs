// Mock working hours for the demo Pros (#65), so "How soon?" can offer only the
// days and blocks somebody is actually free for. There is no real per-day
// availability yet: this is a simple weekly timetable per Pro, seeded
// deterministically from the Pro's id, and nothing else (no bookings, no
// capacity). Writes apps/api/migrations/0022_tradie_hours.sql.
//
//   node data/build-tradie-hours.mjs
//
// The rules, so nobody has to read the code to know what the demo claims:
// - Weekdays for everyone, 7am to 3pm, 4pm or 5pm (outdoor and finishing
//   trades knock off at 3pm). About one Pro in four takes one weekday off.
// - Saturday morning (8am–12pm) for about one Pro in three.
// - Evenings (to 8pm, weekdays) only for after-hours Pros: available now,
//   take the most urgent jobs, in plumbing, electrical or locksmithing, and
//   about half of those. Locksmiths on call also work Saturday and Sunday.
// - Nobody else works evenings or Sundays.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const { tradies } = JSON.parse(readFileSync(join(here, "legwork-demo.json"), "utf8"));

/** FNV-1a, so the same id always gets the same timetable. */
function hash(text) {
  let h = 0x811c9dc5;
  for (const ch of text) h = Math.imul(h ^ ch.charCodeAt(0), 0x01000193) >>> 0;
  return h;
}

const EARLY = new Set(["painting", "tiling", "plastering", "fencing_landscaping", "roofing_gutters"]);
const AFTER_HOURS = new Set(["plumbing", "electrical", "locksmith"]);

const rows = [];
for (const t of tradies) {
  const h = hash(t.id);
  const trade = t.trades[0];
  const afterHours = t.availableNow && t.maxSeverity >= 5 && AFTER_HOURS.has(trade) && (trade === "locksmith" || (h >>> 3) % 2 === 0);
  const end = afterHours ? "20:00" : EARLY.has(trade) ? "15:00" : ["16:00", "17:00"][(h >>> 5) % 2];
  const dayOff = (h >>> 7) % 4 === 0 ? 1 + ((h >>> 9) % 5) : null;
  for (let weekday = 1; weekday <= 5; weekday++) {
    if (weekday !== dayOff) rows.push([t.id, weekday, "07:00", end]);
  }
  if (afterHours && trade === "locksmith") {
    rows.push([t.id, 6, "08:00", "20:00"], [t.id, 0, "09:00", "17:00"]);
  } else if ((h >>> 11) % 3 === 0) {
    rows.push([t.id, 6, "08:00", "12:00"]);
  }
}

const sql = [
  "-- GENERATED by data/build-tradie-hours.mjs - do not hand-edit.",
  "-- Mock weekly working hours for the demo Pros (#65). There is no real per-day",
  "-- availability yet; this timetable is what the \"How soon?\" calendar reads to",
  "-- offer only days and blocks somebody works. See the script for the rules.",
  "-- weekday: 0 Sunday to 6 Saturday. start/end: local \"HH:MM\" in the job's time zone.",
  "CREATE TABLE tradie_hours (",
  "  tradie_id TEXT NOT NULL REFERENCES tradies(id) ON DELETE CASCADE,",
  "  weekday INTEGER NOT NULL CHECK (weekday BETWEEN 0 AND 6),",
  "  start TEXT NOT NULL,",
  "  end TEXT NOT NULL,",
  "  PRIMARY KEY (tradie_id, weekday)",
  ");",
  ...rows.map(([id, weekday, start, end]) => `INSERT INTO tradie_hours (tradie_id, weekday, start, end) VALUES ('${id}', ${weekday}, '${start}', '${end}');`),
  "",
].join("\n");
writeFileSync(join(here, "../apps/api/migrations/0022_tradie_hours.sql"), sql);
console.log(`${rows.length} rows for ${tradies.length} Pros`);
